# task2.py —— 娱乐实验：让两个 AI 互相对话（辩论）
# ============================================================================
#
# 【这个文件是干嘛的？—— 大白话】
# 造了两个性格迥异的 AI 小人，让它们自动来回聊天、互相抬杠：
#   1. 一个"贴吧老哥"（基于 DeepSeek）—— 观点：先有蛋
#   2. 一个"小学生"（基于通义千问）—— 观点：先有鸡
# 然后让它俩自动对话 20 轮，你只需要坐着看戏。
#
# 【它能帮你理解什么？】
# - 多轮对话是怎么实现的：每轮都把"历史记录"带上，AI 才能接着聊。
# - 两个不同的模型（DeepSeek vs 通义千问）怎么在一个程序里配合工作。
# - 一个"全局列表 memory_list"如何被当作"记忆"来反复追加、复用。

# 一个 llm 是基于 ds（DeepSeek）   一个暴躁的贴吧老哥
# 一个 llm 是基于 qwen（通义千问）  一个微博的极端女权（这里实际写的是"小学生"）
from cloud_call.ds_api import ds_chat          # DeepSeek 的一次性问答
from cloud_call.qwen_api import QwenClient     # 通义千问的"多轮对话客户端"类

# ================= 贴吧老哥（DeepSeek） =================
# memory_list 是"贴吧老哥的记忆本"：每次都把新说的话追加进去，
# 再整本发给模型，模型就能"记得"之前聊过什么。
# 小知识：下面 system 的 content 里是两段相邻的字符串字面量，
# Python 会自动把它们拼成一句话（中间没有空格）。
memory_list = [{'role': 'system', 'content':
    '你是一个温柔的但是喜欢阴阳怪气孙吧老哥'
    '你现在正在和一个 小学生 辩论 先有鸡还是先有蛋， 你的观点是先有蛋'}]


def tieba_chat(query: str):
    """让"贴吧老哥"说一句话。

    三步走：
    1. 把用户/对方的话追加到记忆本（role='user'）
    2. 把整本记忆发给 DeepSeek，拿到回复
    3. 把 AI 的回复也追加回记忆本（role='assistant'），这样下一轮还"记得"
    """
    memory_list.append({'role': 'user', 'content': query})   # 记下"对方说了啥"
    res = ds_chat(memory_list)                               # 调 DeepSeek 生成回复
    memory_list.append({'role': 'assistant', 'content': res})# 记下"自己回了啥"
    return res


# ================= 小学生（通义千问） =================
# 这里用 QwenClient 类，它内部自带"记忆"（自动维护多轮上下文），
# 所以不用像上面 memory_list 那样手动维护历史，更省事。
# system_prompt 同样由三段相邻字符串自动拼接成一句话。
extreme = QwenClient(system_prompt="你是一个小学生，"
                                   "你现在正在和一个孙吧老哥辩论"
                                   "先有鸡还是先有蛋， 你的观点是先有鸡")


# ================= 开始自动对话 =================
n = 0                                       # 计数器：控制一共聊多少轮
res1 = extreme('请你先开始和这个孙吧老哥打招呼')   # 让"小学生"先开口打招呼
print(f"小学生: {res1}")

while n < 20:          # 循环 20 轮，让两个 AI 互相"抬杠"

    # 把小学生的打招呼 发给 贴吧老哥
    res2 = tieba_chat(res1)
    print(f"贴吧老哥: {res2}")
    # 把贴吧老哥的回复转述给 小学生
    res3 = extreme(res2)      # extreme(...) 等价于 extreme.ask(...)，靠 __call__ 实现
    print(f"小学生: {res3}")
    res1 = res3               # 把小学生的回答存起来，作为下一轮"贴吧老哥"的输入
    n += 1                    # 计数 +1，避免死循环
